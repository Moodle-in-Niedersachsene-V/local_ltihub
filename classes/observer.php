class observer {
    /**
     * Publish activities that a teacher adds to a hub course later on.
     *
     * @param \core\event\course_module_created $event
     */
    public static function course_module_created(\core\event\course_module_created $event): void {
        global $DB;
        if ($DB->record_exists('local_ltihub_map', ['courseid' => $event->courseid])) {
            local\course_provisioner::publish_activities((int) $event->courseid);
        }
    }
}
